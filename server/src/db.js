import 'dotenv/config';
import pg from 'pg';

const { Pool } = pg;

const connectionString = process.env.DATABASE_URL;
if (!connectionString) {
  throw new Error(
    'DATABASE_URL is required. Add your PostgreSQL connection string (e.g. Supabase) to server/.env ' +
      'or the hosting panel  environment variables.',
  );
}

const ssl =
  process.env.PGSSL === 'false' || process.env.PGSSL === '0'
    ? false
    : { rejectUnauthorized: false };

export const pool = new Pool({ connectionString, ssl, max: 10 });

let tx = null;

async function q(sql, params) {
  const target = tx || pool;
  if (params && params.length) return target.query(sql, params);
  return target.query(sql);
}

export async function query(sql, ...params) {
  const res = await q(sql, params.length ? params : undefined);
  return res.rows;
}

export async function get(sql, ...params) {
  const res = await q(sql, params.length ? params : undefined);
  return res.rows[0];
}

export async function run(sql, ...params) {
  const isInsert = /^\s*insert\s+into/i.test(sql);
  const execSql = isInsert && !/\sreturning\s/i.test(sql) ? `${sql} RETURNING id` : sql;
  const res = await q(execSql, params.length ? params : undefined);
  return {
    lastInsertRowid: res.rows && res.rows.length ? res.rows[0].id : undefined,
    changes: res.rowCount ?? 0,
  };
}

export async function begin() {
  const client = await pool.connect();
  tx = client;
  await client.query('BEGIN');
}

export async function commit() {
  if (!tx) return;
  const client = tx;
  tx = null;
  await client.query('COMMIT');
  client.release();
}

export async function rollback() {
  if (!tx) return;
  const client = tx;
  tx = null;
  try {
    await client.query('ROLLBACK');
  } finally {
    client.release();
  }
}

export async function closePool() {
  await pool.end();
}

const SCHEMA = `
CREATE TABLE IF NOT EXISTS students (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  phone TEXT NOT NULL,
  email TEXT,
  age INTEGER,
  guardian_name TEXT,
  guardian_phone TEXT,
  address TEXT,
  date_of_birth TEXT,
  date_of_admission TEXT,
  notes TEXT,
  status TEXT DEFAULT 'active',
  created_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS courses (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  fee_mode TEXT DEFAULT 'monthly',
  monthly_fee DOUBLE PRECISION NOT NULL DEFAULT 0,
  duration_months INTEGER,
  description TEXT,
  status TEXT DEFAULT 'active',
  admission_fee DOUBLE PRECISION NOT NULL DEFAULT 0,
  kit_fee DOUBLE PRECISION,
  sort_order INTEGER,
  created_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS batches (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name TEXT NOT NULL,
  course_id INTEGER REFERENCES courses(id) ON DELETE SET NULL,
  days TEXT,
  time TEXT,
  status TEXT DEFAULT 'active',
  created_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS enrollments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id INTEGER NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  course_id INTEGER REFERENCES courses(id),
  batch TEXT,
  batch_id INTEGER REFERENCES batches(id) ON DELETE SET NULL,
  start_date TEXT NOT NULL,
  status TEXT DEFAULT 'active',
  notes TEXT,
  created_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS fee_payments (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  enrollment_id INTEGER NOT NULL REFERENCES enrollments(id) ON DELETE CASCADE,
  amount DOUBLE PRECISION NOT NULL,
  payment_date TEXT NOT NULL DEFAULT (CURRENT_DATE),
  method TEXT DEFAULT 'cash',
  notes TEXT,
  fee_type TEXT NOT NULL DEFAULT 'tuition',
  gateway_ref TEXT,
  admission_group TEXT,
  share_token TEXT,
  created_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS reminder_logs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  enrollment_id INTEGER NOT NULL,
  student_id INTEGER NOT NULL,
  amount_due DOUBLE PRECISION,
  channel TEXT DEFAULT 'whatsapp',
  status TEXT,
  message TEXT,
  error TEXT,
  sent_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS users (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email TEXT NOT NULL UNIQUE,
  name TEXT NOT NULL,
  password_hash TEXT NOT NULL,
  recovery_key_hash TEXT,
  role TEXT NOT NULL DEFAULT 'admin',
  active INTEGER NOT NULL DEFAULT 1,
  created_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS sessions (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  token_hash TEXT NOT NULL UNIQUE,
  user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at TIMESTAMPTZ DEFAULT now(),
  expires_at TIMESTAMPTZ NOT NULL,
  last_seen_at TIMESTAMPTZ DEFAULT now()
);

CREATE TABLE IF NOT EXISTS attendance_logs (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id INTEGER NOT NULL REFERENCES batches(id) ON DELETE CASCADE,
  batch_date TEXT NOT NULL,
  notes TEXT,
  created_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
  created_at TIMESTAMPTZ DEFAULT now(),
  UNIQUE(batch_id, batch_date)
);

CREATE TABLE IF NOT EXISTS attendance_entries (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  attendance_id INTEGER NOT NULL REFERENCES attendance_logs(id) ON DELETE CASCADE,
  student_id INTEGER NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  status TEXT NOT NULL,
  UNIQUE(attendance_id, student_id)
);

CREATE TABLE IF NOT EXISTS student_events (
  id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  student_id INTEGER NOT NULL REFERENCES students(id) ON DELETE CASCADE,
  enrollment_id INTEGER REFERENCES enrollments(id) ON DELETE SET NULL,
  type TEXT NOT NULL,
  course_id INTEGER REFERENCES courses(id) ON DELETE SET NULL,
  from_course TEXT,
  to_course TEXT,
  remark TEXT,
  created_at TIMESTAMPTZ DEFAULT now()
);

CREATE INDEX IF NOT EXISTS idx_sessions_user_id ON sessions(user_id);
CREATE INDEX IF NOT EXISTS idx_sessions_expires_at ON sessions(expires_at);
CREATE INDEX IF NOT EXISTS idx_student_events_student_id ON student_events(student_id);
CREATE INDEX IF NOT EXISTS idx_student_events_enrollment_id ON student_events(enrollment_id);
CREATE INDEX IF NOT EXISTS idx_enrollments_student_id ON enrollments(student_id);
CREATE INDEX IF NOT EXISTS idx_fee_payments_enrollment_id ON fee_payments(enrollment_id);
CREATE INDEX IF NOT EXISTS idx_reminder_logs_student_id ON reminder_logs(student_id);
CREATE INDEX IF NOT EXISTS idx_reminder_logs_enrollment_id ON reminder_logs(enrollment_id);
CREATE INDEX IF NOT EXISTS idx_attendance_logs_date ON attendance_logs(batch_date);
CREATE INDEX IF NOT EXISTS idx_attendance_entries_attendance_id ON attendance_entries(attendance_id);
CREATE INDEX IF NOT EXISTS idx_fee_payments_admission_group
  ON fee_payments(admission_group) WHERE admission_group IS NOT NULL;
CREATE UNIQUE INDEX IF NOT EXISTS idx_fee_payments_gateway_ref
  ON fee_payments(gateway_ref) WHERE gateway_ref IS NOT NULL;

CREATE OR REPLACE FUNCTION fee_payments_set_share_token() RETURNS trigger AS $fn$
BEGIN
  IF NEW.share_token IS NULL THEN
    NEW.share_token := lower(substr(md5(random()::text || clock_timestamp()::text), 1, 24));
  END IF;
  RETURN NEW;
END;
$fn$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_fee_payments_share_token ON fee_payments;
CREATE TRIGGER trg_fee_payments_share_token
  BEFORE INSERT ON fee_payments
  FOR EACH ROW EXECUTE FUNCTION fee_payments_set_share_token();
`;

async function ensureSchema() {
  await pool.query(SCHEMA);
}

await ensureSchema();